#!/usr/bin/env python3
"""Record and check the licences of everything Fanimate ships.

    python scripts/licences.py           # rewrite docs/legal/licences.md
    python scripts/licences.py --check   # fail on a disallowed licence or a stale record

Walks the normal (not dev or build) dependencies of the workspace's crates,
on every platform, as `cargo metadata` resolves them from Cargo.lock. A
package passes when at least one alternative of its licence expression is
made only of licences in ALLOWED: the app and engine are MIT/Apache, so no
GPL or LGPL code may be linked in (CLAUDE.md). The record also lists what
ships beside the code: fonts, icons and Rhubarb.
"""

import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "legal" / "licences.md"

# permissive licences, and the font licences of fonts bundled in crates
ALLOWED = {
    "MIT",
    "Apache-2.0",
    "Apache-2.0 WITH LLVM-exception",
    "BSD-2-Clause",
    "BSD-3-Clause",
    "ISC",
    "Zlib",
    "0BSD",
    "Unlicense",
    "BSL-1.0",
    "CC0-1.0",
    "NCSA",
    "Unicode-3.0",
    "Unicode-DFS-2016",
    "OFL-1.1",
    "Ubuntu-font-1.0",
    # file-level copyleft: fine to link unmodified (Symphonia reads MP3, Ogg,
    # FLAC and AAC); changes to such a file must be shared, which we make none of
    "MPL-2.0",
}

# Shipped beside the code, not through Cargo.
BESIDE = [
    ("Inter (UI font)", "OFL-1.1", "brand/fonts"),
    ("JetBrains Mono (frame numbers)", "OFL-1.1", "brand/fonts"),
    ("Noto Sans Arabic, Hebrew, Devanagari and Thai (text in those scripts)", "OFL-1.1", "brand/fonts"),
    ("Lucide icons", "ISC", "crates/fanimate-app/icons/lucide"),
    ("Rhubarb Lip Sync 1.14.0 (separate program)", "MIT", "scripts/fetch-rhubarb.sh"),
]


def alternatives(expr):
    """The ways to satisfy an SPDX-style expression, each a set of licences."""
    expr = expr.replace("/", " OR ").strip()
    while expr.startswith("(") and expr.endswith(")") and balanced(expr[1:-1]):
        expr = expr[1:-1].strip()
    parts = split_top(expr, "OR")
    if len(parts) > 1:
        return [a for p in parts for a in alternatives(p)]
    parts = split_top(expr, "AND")
    if len(parts) > 1:
        combos = [set()]
        for p in parts:
            combos = [c | a for c in combos for a in alternatives(p)]
        return combos
    return [{" ".join(expr.split())}]


def balanced(s):
    depth = 0
    for c in s:
        depth += {"(": 1, ")": -1}.get(c, 0)
        if depth < 0:
            return False
    return depth == 0


def split_top(expr, op):
    """Split on ` op ` outside parentheses."""
    parts, depth, start = [], 0, 0
    tokens = re.split(r"(\(|\)|\s+)", expr)
    out, cur = [], []
    for t in tokens:
        if t == "(":
            depth += 1
        elif t == ")":
            depth -= 1
        if depth == 0 and t == op:
            out.append("".join(cur).strip())
            cur = []
        else:
            cur.append(t)
    out.append("".join(cur).strip())
    return [p for p in out if p]


def chosen(expr):
    """The allowed alternative closest to Fanimate's own licences, or None."""
    def rank(alt):
        return max({"MIT": 0, "Apache-2.0": 1}.get(l, 2) for l in alt)

    allowed = [alt for alt in alternatives(expr) if alt <= ALLOWED]
    if not allowed:
        return None
    return " AND ".join(sorted(min(allowed, key=rank)))


def shipped_packages():
    meta = json.loads(
        subprocess.run(
            ["cargo", "metadata", "--format-version", "1", "--locked"],
            cwd=ROOT,
            check=True,
            capture_output=True,
            text=True,
        ).stdout
    )
    packages = {p["id"]: p for p in meta["packages"]}
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    members = set(meta["workspace_members"])
    seen, todo = set(), list(members)
    while todo:
        pid = todo.pop()
        if pid in seen:
            continue
        seen.add(pid)
        for dep in nodes[pid]["deps"]:
            if any(k["kind"] is None for k in dep["dep_kinds"]):
                todo.append(dep["pkg"])
    return [packages[p] for p in seen - members]


def main():
    check = "--check" in sys.argv[1:]
    rows, bad = [], []
    for p in sorted(shipped_packages(), key=lambda p: (p["name"], p["version"])):
        expr = p.get("license") or ""
        pick = chosen(expr) if expr else None
        if pick is None:
            bad.append(f"{p['name']} {p['version']}: {expr or 'no licence given'}")
        rows.append((p["name"], p["version"], expr, pick or "NOT ALLOWED"))

    counts = {}
    for _, _, _, pick in rows:
        counts[pick] = counts.get(pick, 0) + 1
    lines = [
        "# Licences of what Fanimate ships",
        "",
        "Generated by `python scripts/licences.py` from `Cargo.lock`; do not edit by hand. "
        "`pnpm release` runs it with `--check`, which fails on any dependency without an "
        "MIT/Apache-compatible licence and on a stale record.",
        "",
        "Fanimate itself is MIT or Apache 2.0. Where a crate offers a choice, Fanimate uses it "
        "under the licence in the last column. FFmpeg is not shipped "
        "([video export note](video-export.md)).",
        "",
        "## Shipped beside the code",
        "",
        "| What | Licence | Where |",
        "|---|---|---|",
    ]
    lines += [f"| {what} | {lic} | `{where}` |" for what, lic, where in BESIDE]
    lines += [
        "",
        f"## Rust crates ({len(rows)})",
        "",
        "| Licence used | Crates |",
        "|---|---|",
    ]
    lines += [f"| {k} | {v} |" for k, v in sorted(counts.items(), key=lambda kv: (-kv[1], kv[0]))]
    lines += ["", "| Crate | Version | Licence expression | Used under |", "|---|---|---|---|"]
    lines += [f"| {n} | {v} | {e or '(none)'} | {c} |" for n, v, e, c in rows]
    text = "\n".join(lines) + "\n"

    if bad:
        print("Dependencies without an allowed licence:\n  " + "\n  ".join(bad))
        sys.exit(1)
    if check:
        if not OUT.is_file() or OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT.relative_to(ROOT)} is out of date: run python scripts/licences.py")
            sys.exit(1)
        print(f"Licences checked: {len(rows)} crates, all allowed.")
    else:
        OUT.write_text(text, encoding="utf-8", newline="\n")
        print(f"Wrote {OUT.relative_to(ROOT)}: {len(rows)} crates, all allowed.")


if __name__ == "__main__":
    main()
