#!/usr/bin/env python3
"""Record and check the models Fanimate may ship (decision D2-6).

    python scripts/models.py           # rewrite docs/legal/models.md
    python scripts/models.py --check   # fail on a model that breaks the policy or a stale record

The policy is `models/policy.json`, which the Rust crate `fanimate-ml` reads
too, so the release check and the program judge a model by the same lists.
The set of models is `models/registry.json`. Each entry names a model the
release carries, with its licence and provenance; an entry that fails the
policy fails the check, and so does a record in docs/legal/models.md that is
out of date. With no entries (as today) the record says that no model ships.

An entry looks like (see docs/legal/models.md):

    {"id": "...", "name": "...", "task": "speech_to_text", "version": "...",
     "licence": "MIT", "licence_file": "...", "source": "...", "sha256": "...",
     "provenance": {"training_data": "...", "consent": "donated",
                    "scraped_art": false, "notes": "..."}}
"""

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
POLICY = ROOT / "models" / "policy.json"
REGISTRY = ROOT / "models" / "registry.json"
OUT = ROOT / "docs" / "legal" / "models.md"

TASKS = {
    "line_cleanup", "inbetween_ranking", "auto_rig_keypoints", "colour_assist",
    "lip_sync_alignment", "speech_to_text", "pose_from_photo",
}


def tokens(expr):
    return re.findall(r"\(|\)|[A-Za-z0-9.+_-]+", expr)


def judge(expr, policy):
    """None when the SPDX expression passes, else a sentence saying why not."""
    allowed = set(policy["allowed_licences"])
    toks = tokens(expr)
    if not toks or len(toks) > 40 or re.search(r"[^A-Za-z0-9.+_\-() ]", expr.strip()):
        return "the licence is missing or is not a licence expression"
    pos = 0

    def atom():
        nonlocal pos
        if pos >= len(toks):
            raise ValueError("incomplete")
        t = toks[pos]
        pos += 1
        if t == "(":
            v = parse_or()
            if pos >= len(toks) or toks[pos] != ")":
                raise ValueError("bracket")
            pos += 1
            return v
        if t in ("AND", "OR", ")"):
            raise ValueError("unexpected " + t)
        if t in allowed:
            return None
        low = t.lower()
        if any(term.lower() in low for term in policy["needs_a_lawyer"]):
            return f'"{t}" limits how the weights may be used and needs a lawyer\'s decision'
        return f'"{t}" is not on the list of permissive licences'

    def parse_and():
        nonlocal pos
        v = atom()
        while pos < len(toks) and toks[pos] == "AND":
            pos += 1
            n = atom()
            if v is None:
                v = n
        return v

    def parse_or():
        nonlocal pos
        best = parse_and()
        while pos < len(toks) and toks[pos] == "OR":
            pos += 1
            n = parse_and()
            if best is not None and n is None:
                best = None
        return best

    try:
        verdict = parse_or()
        if pos != len(toks):
            return "the licence is not an expression this check can read"
        return verdict
    except ValueError:
        return "the licence is not an expression this check can read"


def problems(entry, policy):
    out = []
    ident = entry.get("id", "?")
    if not re.fullmatch(r"[a-z0-9][a-z0-9._-]{0,63}", str(ident)):
        out.append("the id must be lower case letters, digits, '.', '-' or '_'")
    if entry.get("task") not in TASKS:
        out.append(f"the task must be one of {', '.join(sorted(TASKS))}")
    for key in ("name", "version", "licence_file", "source"):
        if not str(entry.get(key, "")).strip():
            out.append(f"'{key}' is missing")
    if not re.fullmatch(r"[0-9a-f]{64}", str(entry.get("sha256", ""))):
        out.append("'sha256' must be 64 lower case hex digits")
    why = judge(str(entry.get("licence", "")), policy)
    if why:
        out.append("licence: " + why)
    prov = entry.get("provenance") or {}
    if len(str(prov.get("training_data", "")).strip()) < 20:
        out.append("provenance: say what the model was trained on")
    if prov.get("scraped_art") is not False:
        out.append("provenance: 'scraped_art' must be false (art scraped without consent is never accepted)")
    if prov.get("consent") not in policy["consents"]:
        out.append("provenance: 'consent' must be one of " + ", ".join(policy["consents"]))
    return out


def render(policy, models):
    lines = [
        "# Models Fanimate ships",
        "",
        "Generated by `python scripts/models.py` from `models/registry.json`; do not edit by hand. "
        "`pnpm release` runs it with `--check`, which fails on a model that breaks the policy and on a stale record.",
        "",
        "## The policy (decision D2-6)",
        "",
        "**Permissive redistribution licences only; documented provenance; commissioned or donated data "
        "for any model Fanimate trains; no scraped art.** The lists below are `models/policy.json`, which the "
        "program (`fanimate-ml`) and this check both read.",
        "",
        "- **Licences allowed** for weights: " + ", ".join(f"`{l}`" for l in policy["allowed_licences"]) + ". "
        "An expression passes when one alternative of every `OR` is made only of these (`AND` needs all).",
        "- **Needs a lawyer before any model under it is added:** a licence that limits how the weights may be used, "
        "that is, a name containing " + ", ".join(f"`{t}`" for t in policy["needs_a_lawyer"]) + ". "
        "Responsible-AI, non-commercial, research-only and community licences with a use policy are all in this group. "
        "They are never allowed by default.",
        "- **Provenance** is recorded for every model: what it was trained on, and how the data was gathered: "
        + ", ".join(f"`{c}`" for c in policy["consents"]) + ". `unknown` is refused, and so is any model "
        "trained on art gathered from the web without its artists' consent.",
        "- **A model Fanimate trains itself** uses commissioned or donated data with written consent, never "
        "scraped art and never the projects of Fanimate's users.",
        "- **Packaging:** each model is a `.fnmodel` file, signed with the Ed25519 scheme that signs updates, "
        "with its SHA-256 and licence file inside; Fanimate verifies all of it when installing and again every "
        "time the model is loaded, and loads nothing while AI features are off. See `crates/fanimate-ml`.",
        "",
        "## Models in this release",
        "",
    ]
    if not models:
        lines += [
            "**None.** No model is bundled or offered for download in this release. The model manager, the "
            "signing and the checks are built and tested; a model is added to `models/registry.json` only after "
            "its weights licence, its training-data provenance and its quality on Fanimate's own test sets have "
            "been recorded and reviewed. The classical tools (line clean-up, inbetween assist and auto-rig) need "
            "no model.",
            "",
        ]
    else:
        lines += [
            "| Model | Task | Version | Licence | Provenance | Source | SHA-256 |",
            "|---|---|---|---|---|---|---|",
        ]
        for m in models:
            prov = m["provenance"]
            lines.append(
                f"| {m['name']} (`{m['id']}`) | {m['task']} | {m['version']} | {m['licence']} "
                f"(`{m['licence_file']}`) | {prov['consent']}: {prov['training_data']} | {m['source']} | `{m['sha256']}` |"
            )
        lines.append("")
    return "\n".join(lines)


def main():
    check = "--check" in sys.argv[1:]
    policy = json.loads(POLICY.read_text(encoding="utf-8"))
    registry = json.loads(REGISTRY.read_text(encoding="utf-8"))
    models = registry.get("models", [])
    failed = False
    seen = set()
    for m in models:
        found = problems(m, policy)
        if m.get("id") in seen:
            found.append("the id is used twice")
        seen.add(m.get("id"))
        for p in found:
            failed = True
            print(f"models/registry.json: {m.get('id', '?')}: {p}", file=sys.stderr)
    text = render(policy, models)
    if check:
        have = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if have.replace("\r\n", "\n") != text.replace("\r\n", "\n"):
            print("docs/legal/models.md is out of date: run python scripts/models.py", file=sys.stderr)
            failed = True
        if failed:
            sys.exit(1)
        print(f"Models checked: {len(models)} in the registry, policy holds.")
        return
    if failed:
        sys.exit(1)
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(models)} models)")


if __name__ == "__main__":
    main()
